// Function to send a byte via USART2
int uart2_write( int ch )
{
	/*Wait until Transmit Data Register Empty (TXE = 1)
	  While TXE is 0, it means the previous data has not yet been moved
	*/
	while( !(USART2->SR & 0x0080)){}

	//Write the lower 8 bits of 'ch' into the Data Register (DR) for transmission
	USART2-> DR = ( ch & 0xFF );
	return ch;
}

int _io__putchar( int ch)
{
	uart2_write( ch);
	return ch;
}

// Task1 to send data to the queue
void senderTask(void *PvParameters)
{
	BaseType_t qstatus;
	while(1)
	{
		const TickType_t time = pdMS_TO_TICKS(200);
		// Try to send data to the queue without blocking
		qstatus = xQueueSend(queue, &PvParameters, time);
		if(qstatus != pdPASS)
		{
			// Print error if queue is full
			printf("Error: data could not be send....\r\n");
			for(int i=0; i<1000000; i++);
		}
	}
}


// Task to receive data from the queue
void receiverTask(void *PvParameters)
{
	BaseType_t qstatus;
	data_t received_data ;
	while(1)
	{
		// Try to receive data from the queue
		qstatus = xQueueReceive(queue,&received_data, 0);
		if(qstatus == pdPASS)
		{
		  // check data from which sensor
		  if( received_data.Data_source == temperature_sensor)
		  {
			  printf("Recived temperature value is %d \r\n", received_data.value);
		  }
		  else
			  printf("Recived ultrasonic value is %d \r\n", received_data.value);
		}
		else
			// Print error if no data received within timeout
			printf("error on reading...\n\r");
	}
}

