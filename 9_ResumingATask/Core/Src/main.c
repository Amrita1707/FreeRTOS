void led1ControllerTask(void *PvParameters)
{
	int i;
	while(1)
	{
		led1++;
		for(i=0; i<100000;i++);
		SuspendLed1_Task++;
		//When SuspendLed1_Task reached greater than 50 Led1 controller will suspend
		if(SuspendLed1_Task > 50)
		{
			is_suspend = true;
			SuspendLed1_Task = 0;
			//Suspend the task itself
			vTaskSuspend(NULL);
		}
	}
}

void led2ControllerTask(void *PvParameters)
{
	int i;
	while(1)
	{
		led2++;
		for(i=0; i<100000;i++);
		if(is_suspend)
		{
			ResumeLed1_Task++;
			//When ResumeLed1_Task reached greater than 50 Led1 controller will resume
			if(ResumeLed1_Task > 50)
			{
				//Resume the Led1 controller task
				vTaskResume(Led1Handle);
				ResumeLed1_Task = 0;
				is_suspend = false;
			}
		}
	}
}

void led3ControllerTask(void *PvParameters)
{

	int i;
	while(1)
	{
		led3++;
		for(i=0; i<100000;i++);
	}
}

